IPIFY_URL = "https://api.ipify.org"
DEFAULT_PORT = 8765
STATUS_POLL_TIMEOUT = 2.0
SPAWN_WAIT_ATTEMPTS = 12   # ~6s total at 500ms apiece


def fetch_public_ip(timeout: float = 5.0) -> str:
    with urllib.request.urlopen(IPIFY_URL, timeout=timeout) as resp:
        return resp.read().decode().strip()


def check_node_status(meta: dict, timeout: float = STATUS_POLL_TIMEOUT) -> dict | None:
    """Returns the parsed /api/cells response if the local headless node
    answers, else None (not running, still starting up, or unreachable)."""
    url = f"http://127.0.0.1:{meta['port']}/nevod-admin/api/cells"
    req = urllib.request.Request(url)
    auth = base64.b64encode(f"{meta.get('username', '')}:{meta['password']}".encode()).decode()
    req.add_header("Authorization", f"Basic {auth}")
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return json.loads(resp.read())
    except Exception:
        return None


def spawn_node_process():
    """Launches the headless node as a fully detached background process —
    survives this wizard process exiting."""
    cmd = node_exe_command()
    kwargs = dict(stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                 stderr=subprocess.DEVNULL, close_fds=True)
    if sys.platform == "win32":
        kwargs["creationflags"] = subprocess.CREATE_NO_WINDOW | subprocess.DETACHED_PROCESS
    subprocess.Popen(cmd, **kwargs)


def kill_node_process():
    """Stops the headless node process by the PID it recorded at startup
    (installer/node_headless.py:write_pid) — best-effort, used by uninstall."""
    pid = read_pid()
    if pid is None:
        return
    try:
        if sys.platform == "win32":
            subprocess.run(["taskkill", "/F", "/PID", str(pid)],
                           capture_output=True, timeout=10)
        else:
            import signal
            os.kill(pid, signal.SIGTERM)
    except Exception:
        pass  # already gone, or we don't have permission — nothing more we can do


def perform_uninstall():
    """Stops the node, disables autostart, deletes local install files.
    Used both by the wizard's own "Удалить установку" button and headlessly
    via `nevod-gui.exe --uninstall-cleanup` — Inno Setup's [UninstallRun]
    calls that flag before removing the installed exes, so the real OS
    uninstaller also cleans up state file-removal alone wouldn't touch: the
    still-running background process, the autostart registry entry, and
    identity/db files that live outside the install directory."""
    kill_node_process()
    try:
        autostart.disable()
    except Exception:
        pass
    for p in (identity_path(), db_path(), admin_meta_path(), pid_path()):
        try:
            p.unlink(missing_ok=True)
        except Exception:
            pass


class NodeRunner:
    """Owns a background thread + its own asyncio event loop, used ONLY for
    the join flow — we need a real Node instance to make the join()
    request/response round-trip with the recommender. Once join() succeeds
    and identity/db are saved to disk, this temporary node is cleanly shut
    down (stop_and_wait) and the long-running headless process takes over
    the same identity/db and re-binds the port."""

    def __init__(self):
        self.loop: asyncio.AbstractEventLoop | None = None
        self.thread: threading.Thread | None = None
        self.node = None
        self.reachable: bool | None = None
        self.upnp_forwarded: bool = False
        self.result_queue: queue.Queue = queue.Queue()

    def start_join(self, my_identity_path: Path, my_db_path: Path,
                   my_address: str, bootstrap_addr: str,
                   tls_fingerprint: str, invite_code: str, node_name: str = ""):
        self.thread = threading.Thread(
            target=self._run_join,
            args=(my_identity_path, my_db_path, my_address, bootstrap_addr,
                  tls_fingerprint, invite_code, node_name),
            daemon=True,
        )
        self.thread.start()

    def _run_join(self, my_identity_path, my_db_path, my_address, bootstrap_addr,
                  tls_fingerprint, invite_code, node_name=""):
        from node.identity import NodeIdentity

        # Best-effort, blocking (~2s), done before the event loop starts so it
        # doesn't stall anything async — if it fails/UPnP is off, the join's
        # own reachability test (node/node.py:_test_reachability) is what
        # actually tells the user whether they still need to forward the
        # port manually.
        try:
            port_str = my_address.rsplit(":", 1)[-1]
            if port_str.isdigit():
                from netcheck import try_forward_port
                self.upnp_forwarded = try_forward_port(int(port_str))
        except Exception:
            pass

        self.loop = asyncio.new_event_loop()
        asyncio.set_event_loop(self.loop)

        async def setup():
            from node.node import Node

            identity = NodeIdentity.generate(my_address, name=node_name)
            identity.save(str(my_identity_path))

            # identity.address is the PUBLIC address other peers dial — the
            # local socket almost always can't bind that exact address
            # behind NAT, so bind broadly and let the public address be
            # purely advertised, not bound to.
            os.environ["NEVOD_BIND"] = "0.0.0.0"

            node = await Node.create(str(my_identity_path), str(my_db_path))
            await node.start()
            if bootstrap_addr:
                self.reachable = await node.join(bootstrap_addr, expected_fingerprint=tls_fingerprint,
                                                 invite_code=invite_code)
            # else: autonomous — no bootstrap to connect to or test reachability against.
            # self.reachable stays None (its __init__ default), which _screen_done already
            # treats as "no reachability message" rather than a false negative.
            return node

        try:
            self.node = self.loop.run_until_complete(setup())
        except Exception as e:
            self.result_queue.put(("error", e))
            return
        self.result_queue.put(("ok", self.node))
        self.loop.run_forever()

    def stop_and_wait(self, timeout: float = 5.0):
        """Cleanly closes the temp node's listening socket + DB connection
        and waits for the thread to actually exit, so the port and DB file
        are free before spawning the headless process that takes over."""
        if not self.loop or not self.thread:
            return

        async def _shutdown():
            if self.node:
                await self.node.stop()
            self.loop.stop()

        fut = asyncio.run_coroutine_threadsafe(_shutdown(), self.loop)
        try:
            fut.result(timeout=timeout)
        except Exception:
            pass
        self.thread.join(timeout=timeout)


class WizardApp(tk.Tk):
    def __init__(self):
        super().__init__()
        self.title("Nevod — установка узла")
        self.geometry("480x480")
        self.resizable(False, False)
        self.protocol("WM_DELETE_WINDOW", self.destroy)

        self.runner = NodeRunner()
        self.identity_path = identity_path()
        self.db_path = db_path()

        self._token = ""
        self._bootstrap_addr = ""
        self._tls_fingerprint = ""
        self._invite_code = ""
        self._public_ip = ""
        self._node_name = ""
        self._admin_username = ""
        self._admin_password = ""

        self._frame: ttk.Frame | None = None
        self._status_queue: queue.Queue = queue.Queue()    # (meta, data) tuples
        self._handoff_queue: queue.Queue = queue.Queue()   # (node_id, address, name, reachable, upnp_forwarded)

        if self.identity_path.exists():
            self._screen_checking_status()
        else:
            self._screen_welcome()

    # ── frame helpers ───────────────────────────────────────────────────

    def _set_frame(self, builder):
        if self._frame is not None:
            self._frame.destroy()
        self._frame = ttk.Frame(self, padding=24)
        self._frame.pack(fill="both", expand=True)
        builder(self._frame)

    # ── screen: checking whether the headless node is already running ───

    def _screen_checking_status(self):
        self._screen_progress("Проверяем статус узла…")

        def check():
            meta = ensure_admin_meta()
            data = check_node_status(meta)
            self._status_queue.put((meta, data))
        threading.Thread(target=check, daemon=True).start()
        self.after(150, self._poll_status_check)

    def _poll_status_check(self):
        try:
            meta, data = self._status_queue.get_nowait()
        except queue.Empty:
            self.after(150, self._poll_status_check)
            return
        if data is not None:
            self._screen_status_running(meta, data)
        else:
            self._screen_status_stopped(meta)

    # ── screen: headless node confirmed running ──────────────────────────

    def _screen_status_running(self, meta: dict, data: dict):
        def build(f):
            ttk.Label(f, text="Узел работает в фоне ✓", font=("", 16, "bold"),
                     foreground="#27ae60").pack(pady=(0, 12))
            node_name = data.get("node_name", "")
            ttk.Label(
                f,
                text=(f"название: {node_name}\n" if node_name else "")
                     + f"node_id:  {data.get('node_id', '?')[:16]}…\n"
                       f"адрес:    {data.get('address', '?')}",
                justify="left",
            ).pack(pady=(0, 16))
            autostart_var = tk.StringVar(
                value="Автозапуск при включении компьютера: включён"
                if autostart.is_enabled() else
                "Автозапуск при включении компьютера: выключен")
            ttk.Label(f, textvariable=autostart_var, wraplength=420, justify="left").pack(pady=(0, 20))

            def open_admin():
                webbrowser.open(f"http://127.0.0.1:{meta['port']}/nevod-admin")

            def toggle_autostart():
                exe = frozen_node_exe_path()
                if autostart.is_enabled():
                    autostart.disable()
                elif exe:
                    autostart.enable(exe)
                autostart_var.set(
                    "Автозапуск при включении компьютера: включён"
                    if autostart.is_enabled() else
                    "Автозапуск при включении компьютера: выключен")

            ttk.Button(f, text="Открыть admin-панель", command=open_admin).pack(pady=(0, 8))
            ttk.Button(f, text="Вкл./выкл. автозапуск", command=toggle_autostart).pack(pady=(0, 16))
            ttk.Button(f, text="Удалить установку", command=self._confirm_uninstall).pack()
        self._set_frame(build)

    # ── screen: headless node not responding ─────────────────────────────

    def _screen_status_stopped(self, meta: dict):
        def build(f):
            ttk.Label(f, text="Узел настроен, но не запущен", font=("", 14, "bold")).pack(pady=(0, 12))
            ttk.Label(
                f, text=f"Конфигурация найдена: {self.identity_path}",
                wraplength=420, justify="left",
            ).pack(pady=(0, 20))
            ttk.Button(f, text="Запустить сейчас", command=lambda: self._start_headless(meta)).pack(pady=(0, 16))
            ttk.Button(f, text="Удалить установку", command=self._confirm_uninstall).pack()
        self._set_frame(build)

    # ── uninstall ─────────────────────────────────────────────────────────

    def _confirm_uninstall(self):
        if not messagebox.askyesno(
            "Удалить установку?",
            "Узел будет остановлен, автозапуск отключён, локальные файлы "
            "(node.json, node.db, admin.json) удалены.\n\n"
            "Регистрация этого узла в сети сама исчезнет из списков других "
            "узлов через 72 часа простоя — удалять её вручную не нужно.\n\n"
            "Продолжить?",
        ):
            return
        self._screen_progress("Удаляем установку…")
        threading.Thread(target=self._do_uninstall, daemon=True).start()

    def _do_uninstall(self):
        perform_uninstall()
        self._status_queue.put(("uninstalled", None))
        self.after(150, self._poll_uninstall)

    def _poll_uninstall(self):
        try:
            self._status_queue.get_nowait()
        except queue.Empty:
            self.after(150, self._poll_uninstall)
            return
        self._token = self._bootstrap_addr = self._tls_fingerprint = ""
        self._invite_code = self._public_ip = self._node_name = ""
        self._admin_username = self._admin_password = ""
        self._screen_welcome()

    def _start_headless(self, meta: dict):
        self._screen_progress("Запускаем узел…")
        exe = frozen_node_exe_path()
        try:
            if exe:
                autostart.enable(exe)
        except Exception:
            pass  # best-effort — node still runs even if autostart registration fails
        spawn_node_process()
        threading.Thread(target=self._wait_for_headless, args=(meta,), daemon=True).start()
        self.after(500, self._poll_status_check)

    def _wait_for_headless(self, meta: dict):
        for _ in range(SPAWN_WAIT_ATTEMPTS):
            data = check_node_status(meta)
            if data is not None:
                self._status_queue.put((meta, data))
                return
            import time
            time.sleep(0.5)
        self._status_queue.put((meta, None))

    # ── screen 1: welcome ────────────────────────────────────────────────

    def _screen_welcome(self):
        def build(f):
            ttk.Label(f, text="Nevod", font=("", 20, "bold")).pack(pady=(0, 4))
            ttk.Label(f, text="Установка узла сети Nevod").pack(pady=(0, 20))
            ttk.Label(
                f,
                text="Понадобится инвайт-токен от участника, который уже "
                     "есть в сети — его можно получить в admin-панели его узла "
                     "(раздел «Приглашения нод»).",
                wraplength=420, justify="left",
            ).pack(pady=(0, 24))
            ttk.Button(f, text="Далее →", command=self._screen_token).pack()
        self._set_frame(build)

    # ── screen 2: invite token ──────────────────────────────────────────

    def _screen_token(self):
        def build(f):
            ttk.Label(f, text="Инвайт-токен", font=("", 14, "bold")).pack(pady=(0, 12))
            row = ttk.Frame(f)
            row.pack(fill="x")
            ttk.Label(row, text="Вставьте токен, полученный от существующего узла:").pack(side="left")
            text = tk.Text(f, height=4, wrap="char")
            text.pack(fill="x", pady=(6, 6))
            text.insert("1.0", self._token)

            def paste_from_clipboard(event=None):
                try:
                    clip = self.clipboard_get()
                except tk.TclError:
                    return "break"
                text.delete("1.0", "end")
                text.insert("1.0", clip.strip())
                return "break"

            # Ctrl+V's default Tk binding matches the Latin keysym "v" — under a
            # Cyrillic (or other non-Latin) keyboard layout the physical V key
            # produces a different keysym, so the built-in paste silently no-ops.
            # keycode 86 is the physical V key regardless of active layout.
            text.bind("<Control-KeyPress>",
                     lambda e: paste_from_clipboard() if e.keycode == 86 else None)
            ttk.Button(row, text="📋 Вставить из буфера", command=paste_from_clipboard).pack(side="right")

            error_var = tk.StringVar()
            ttk.Label(f, textvariable=error_var, foreground="#c0392b", wraplength=420).pack(anchor="w")

            def on_next():
                token = text.get("1.0", "end").strip()
                from node.protocol import parse_node_invite_token
                try:
                    address, fingerprint, code = parse_node_invite_token(token)
                except ValueError as e:
                    error_var.set(str(e))
                    return
                self._token = token
                self._bootstrap_addr = address
                self._tls_fingerprint = fingerprint
                self._invite_code = code
                self._screen_setup_info()

            def on_autonomous():
                # Node still gets its own identity/address/admin panel below — "autonomous"
                # means it never registers with the wider Nevod network (no join() call at
                # all, see NodeRunner._run_join), not that it has no address of its own. It
                # still serves its own devices exactly like a normal node.
                self._token = self._bootstrap_addr = self._tls_fingerprint = self._invite_code = ""
                self._screen_setup_info()

            ttk.Label(f, text="или", foreground="#888").pack(pady=(12, 4))
            ttk.Button(f, text="Работать автономно (без подключения к сети)",
                      command=on_autonomous).pack()

            btns = ttk.Frame(f)
            btns.pack(fill="x", pady=(16, 0))
            ttk.Button(btns, text="← Назад", command=self._screen_welcome).pack(side="left")
            ttk.Button(btns, text="Далее →", command=on_next).pack(side="right")
        self._set_frame(build)

    # ── screen 2b: node name + admin credentials ─────────────────────────

    def _screen_setup_info(self):
        def build(f):
            ttk.Label(f, text="Название и администратор", font=("", 14, "bold")).pack(pady=(0, 12))

            ttk.Label(f, text="Название узла (видно другим участникам сети):").pack(anchor="w")
            name_var = tk.StringVar(value=self._node_name)
            ttk.Entry(f, textvariable=name_var).pack(fill="x", pady=(4, 12))

            ttk.Label(f, text="Имя администратора admin-панели:").pack(anchor="w")
            user_var = tk.StringVar(value=self._admin_username)
            ttk.Entry(f, textvariable=user_var).pack(fill="x", pady=(4, 12))

            ttk.Label(f, text="Пароль администратора:").pack(anchor="w")
            pass_row = ttk.Frame(f)
            pass_row.pack(fill="x", pady=(4, 12))
            pass_var = tk.StringVar(value=self._admin_password)
            pass_entry = ttk.Entry(pass_row, textvariable=pass_var, show="*")
            pass_entry.pack(side="left", fill="x", expand=True)

            def toggle_show():
                pass_entry.config(show="" if pass_entry.cget("show") == "*" else "*")
            ttk.Button(pass_row, text="👁", width=3, command=toggle_show).pack(side="left", padx=(6, 0))

            error_var = tk.StringVar()
            ttk.Label(f, textvariable=error_var, foreground="#c0392b", wraplength=420).pack(anchor="w")

            def on_next():
                name = name_var.get().strip()
                user = user_var.get().strip()
                pwd = pass_var.get()
                if not name:
                    error_var.set("Укажите название узла.")
                    return
                if not user:
                    error_var.set("Укажите имя администратора.")
                    return
                if not pwd:
                    error_var.set("Укажите пароль администратора.")
                    return
                self._node_name = name
                self._admin_username = user
                self._admin_password = pwd
                self._screen_address()

            btns = ttk.Frame(f)
            btns.pack(fill="x", pady=(4, 0))
            ttk.Button(btns, text="← Назад", command=self._screen_token).pack(side="left")
            ttk.Button(btns, text="Далее →", command=on_next).pack(side="right")
        self._set_frame(build)

    # ── screen 3: address / port ────────────────────────────────────────

    def _screen_address(self):
        def build(f):
            ttk.Label(f, text="Адрес узла", font=("", 14, "bold")).pack(pady=(0, 12))
            ip_var = tk.StringVar(value="определяем IP…")
            ttk.Label(f, text="Публичный IP-адрес этого компьютера:").pack(anchor="w")
            ip_entry = ttk.Entry(f, textvariable=ip_var)
            ip_entry.pack(fill="x", pady=(4, 12))

            ttk.Label(f, text="Порт (должен быть проброшен на роутере, если это домашняя сеть):").pack(anchor="w")
            port_var = tk.StringVar(value=str(DEFAULT_PORT))
            ttk.Entry(f, textvariable=port_var).pack(fill="x", pady=(4, 12))

            error_var = tk.StringVar()
            ttk.Label(f, textvariable=error_var, foreground="#c0392b", wraplength=420).pack(anchor="w")

            def fetch():
                try:
                    ip = fetch_public_ip()
                except Exception:
                    ip = ""
                    error_var.set("Не удалось определить IP автоматически — введите вручную.")
                if ip:
                    ip_var.set(ip)
                else:
                    ip_var.set("")
            threading.Thread(target=fetch, daemon=True).start()

            def on_next():
                ip = ip_var.get().strip()
                port_str = port_var.get().strip()
                if not ip or ip.endswith("…"):
                    error_var.set("Укажите публичный IP-адрес.")
                    return
                if not port_str.isdigit():
                    error_var.set("Порт должен быть числом.")
                    return
                self._public_ip = f"{ip}:{port_str}"
                self._screen_confirm()

            btns = ttk.Frame(f)
            btns.pack(fill="x", pady=(16, 0))
            ttk.Button(btns, text="← Назад", command=self._screen_setup_info).pack(side="left")
            ttk.Button(btns, text="Далее →", command=on_next).pack(side="right")
        self._set_frame(build)

    # ── screen 4: confirm + register ────────────────────────────────────

    def _screen_confirm(self):
        def build(f):
            ttk.Label(f, text="Подтверждение", font=("", 14, "bold")).pack(pady=(0, 12))
            connection_line = (f"Подключение к:      {self._bootstrap_addr}" if self._bootstrap_addr
                               else "Режим:              автономный (без подключения к сети)")
            ttk.Label(
                f,
                text=f"Название узла:      {self._node_name}\n"
                     f"Адрес этого узла:  {self._public_ip}\n"
                     f"{connection_line}",
                justify="left",
            ).pack(anchor="w", pady=(0, 20))
            btns = ttk.Frame(f)
            btns.pack(fill="x")
            ttk.Button(btns, text="← Назад", command=self._screen_address).pack(side="left")
            confirm_text = "Зарегистрировать узел" if self._bootstrap_addr else "Запустить узел"
            ttk.Button(btns, text=confirm_text, command=self._start_join).pack(side="right")
        self._set_frame(build)

    def _start_join(self):
        progress_text = "Регистрируем узел в сети…" if self._bootstrap_addr else "Запускаем узел…"
        self._screen_progress(progress_text)
        self.runner.start_join(
            self.identity_path, self.db_path, self._public_ip,
            self._bootstrap_addr, self._tls_fingerprint, self._invite_code,
            self._node_name,
        )
        self.after(150, self._poll_join)

    def _poll_join(self):
        try:
            kind, payload = self.runner.result_queue.get_nowait()
        except queue.Empty:
            self.after(150, self._poll_join)
            return
        if kind == "error":
            self._screen_error(str(payload), retry=self._screen_confirm)
        else:
            self._handoff_to_headless(payload)

    def _handoff_to_headless(self, node):
        """Join succeeded via the temp in-process node — shut it down
        cleanly, then hand the same identity/db off to the real long-running
        headless process and register it for autostart."""
        node_id, address, name = node.identity.node_id, node.identity.address, node.identity.name
        reachable = self.runner.reachable
        upnp_forwarded = self.runner.upnp_forwarded
        self._screen_progress("Запускаем фоновый процесс узла…")

        def handoff():
            self.runner.stop_and_wait()
            meta = write_admin_meta(self._admin_password, port=DEFAULT_ADMIN_PORT,
                                    username=self._admin_username)
            exe = frozen_node_exe_path()
            try:
                if exe:
                    autostart.enable(exe)
            except Exception:
                pass  # best-effort — registration succeeded regardless
            spawn_node_process()
            for _ in range(SPAWN_WAIT_ATTEMPTS):
                if check_node_status(meta) is not None:
                    break
                import time
                time.sleep(0.5)
            self._handoff_queue.put((node_id, address, name, reachable, upnp_forwarded))

        threading.Thread(target=handoff, daemon=True).start()
        self.after(150, self._poll_handoff)

    def _poll_handoff(self):
        try:
            node_id, address, name, reachable, upnp_forwarded = self._handoff_queue.get_nowait()
        except queue.Empty:
            self.after(150, self._poll_handoff)
            return
        self._screen_done(node_id, address, name, reachable, upnp_forwarded)

    # ── screen: progress ─────────────────────────────────────────────────

    def _screen_progress(self, message: str):
        def build(f):
            ttk.Label(f, text=message, font=("", 12)).pack(pady=(60, 16))
            bar = ttk.Progressbar(f, mode="indeterminate", length=300)
            bar.pack()
            bar.start(12)
        self._set_frame(build)

    # ── screen: error ────────────────────────────────────────────────────

    def _screen_error(self, message: str, retry):
        def build(f):
            ttk.Label(f, text="Не получилось", font=("", 14, "bold"), foreground="#c0392b").pack(pady=(0, 12))
            ttk.Label(f, text=message, wraplength=420, justify="left").pack(pady=(0, 24))
            btns = ttk.Frame(f)
            btns.pack(fill="x")
            if retry:
                ttk.Button(btns, text="← Назад", command=retry).pack(side="left")
            ttk.Button(btns, text="Выход", command=self.destroy).pack(side="right")
        self._set_frame(build)

    # ── screen: done ─────────────────────────────────────────────────────

    def _screen_done(self, node_id: str, address: str, name: str = "",
                     reachable: bool | None = None, upnp_forwarded: bool = False):
        def build(f):
            ttk.Label(f, text="Готово ✓", font=("", 16, "bold"), foreground="#27ae60").pack(pady=(0, 12))
            ttk.Label(
                f,
                text=(f"название: {name}\n" if name else "")
                     + f"node_id:  {node_id[:16]}…\n"
                       f"адрес:    {address}",
                justify="left",
            ).pack(pady=(0, 20))
            if reachable is True:
                msg = "✓ Проверка доступности: узел виден снаружи"
                if upnp_forwarded:
                    msg += " (порт проброшен автоматически через UPnP)"
                ttk.Label(f, text=msg, foreground="#27ae60",
                         wraplength=420, justify="left").pack(pady=(0, 12))
            elif reachable is False:
                ttk.Label(
                    f,
                    text="⚠ Проверка доступности: узел НЕ отвечает по указанному адресу. "
                         "Другие участники сети не смогут подключиться, пока это не исправлено — "
                         "проверьте проброс порта на роутере и настройки VPN/файрвола.",
                    foreground="#c0392b", wraplength=420, justify="left",
                ).pack(pady=(0, 12))
            elif not self._bootstrap_addr:
                ttk.Label(
                    f, text="ℹ Автономный режим: узел не подключён к общей сети Nevod, "
                            "обслуживает только свои устройства.",
                    foreground="#555", wraplength=420, justify="left",
                ).pack(pady=(0, 12))
            ttk.Label(
                f,
                text="Узел работает в фоне и запустится автоматически при "
                     "следующем включении компьютера. Это окно можно закрыть.",
                wraplength=420, justify="left",
            ).pack(pady=(0, 20))
            ttk.Button(f, text="Закрыть", command=self.destroy).pack()
        self._set_frame(build)


