"""
Nevod node installer wizard (M1 + M2).

A Tkinter GUI that walks a non-technical user through joining the Nevod
network via an invite token (see node/protocol.py:make_node_invite_token,
generated by an existing node's admin panel). On success, hands the node
off to a separate headless background process (installer/node_headless.py)
registered for autostart at login (installer/autostart.py) — closing this
window does not stop the node.

Run from source:  python installer/wizard.py
Frozen build:     see installer/data/nevod-gui.spec (PyInstaller)
"""

